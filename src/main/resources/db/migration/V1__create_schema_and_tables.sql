CREATE TABLE CONVERSATIONS (
    ID UUID PRIMARY KEY,
    TITLE VARCHAR(100),
    CREATED_AT TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UPDATED_AT TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE CONVERSATION_MESSAGES (
    ID UUID PRIMARY KEY,
    CONVERSATION_ID UUID NOT NULL,
    ROLE VARCHAR(20) NOT NULL,
    CONTENT TEXT NOT NULL,
    CREATED_AT TIMESTAMPTZ NOT NULL,
    CONSTRAINT FK_CONVERSATION_MESSAGES_CONVERSATION FOREIGN KEY (conversation_id) REFERENCES conversations(id),
    CONSTRAINT CHK_CONVERSATION_MESSAGE_ROLE CHECK (role IN ('USER', 'ASSISTANT'))
);

CREATE INDEX IDX_CONVERSATION_MESSAGES_HISTORY ON CONVERSATION_MESSAGES (conversation_id, id);
